// finding the gallery element in the DOM
const galleryList = document.querySelector(".gallery");

// create markup for each image
function createGallery(images) {
  // map for each image and return markup
  return images
    .map(
      ({ preview, original, description }) => `<li class="gallery-item">
        <a class="gallery-link" href="${original}">
          <img
            class="gallery-image"
            src="${preview}"
            data-source="${original}"
            alt="${description}"
          />
        </a>
      </li>`,
    )
    .join("");
}

// render gallery on the page
galleryList.insertAdjacentHTML("beforeend", createGallery(images));

// click handler for opening modal window
function galleryClick(event) {
  event.preventDefault();
  if (!event.target.classList.contains("gallery-image")) return;

  // getting the source of the image
  const currentImageSrc = event.target.dataset.source;
  // create modal
  const instance = basicLightbox.create(
    `<img src="${currentImageSrc}" alt="${event.target.alt}">`,
    {
      // handler for open modal window
      onShow: () => {
        document.addEventListener("keydown", onModalClose);
      },
      // handler for close modal window for Escape key for remove event listener to clear memory
      onClose: () => {
        document.removeEventListener("keydown", onModalClose);
      },
    },
  );

  // close modal window
  function onModalClose(event) {
    if (event.code === "Escape") {
      instance.close();
    }
  }
  // show modal window
  instance.show();
}

// add event listener for gallery
galleryList.addEventListener("click", galleryClick);
